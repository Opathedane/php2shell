package audit

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
	"time"
)

// TestWriteReadmeExampleAsset regenerates docs/assets/report-example-patch-assessment.html
// when PHP2SHELL_WRITE_README_ASSET=1. Synthetic lab host "old-php" only — no customer data.
func TestWriteReadmeExampleAsset(t *testing.T) {
	if os.Getenv("PHP2SHELL_WRITE_README_ASSET") != "1" {
		t.Skip("set PHP2SHELL_WRITE_README_ASSET=1 to regenerate README example HTML")
	}
	r := NewReport("old-php", "linux", "amd64")
	r.GeneratedUTC = time.Date(2026, 10, 27, 12, 0, 0, 0, time.UTC)
	r.AddCheck("packages", "PARTIAL", "ok")
	r.AddCheck("binary_paths", "PARTIAL", "Found 1 PHP-like binary paths across 1 install director(ies) (1 with verified static version markers, 0 path-inferred, 0 without comparable version); path-inferred versions are not binary-verified and are not proof of the HTTP-serving runtime; no binaries executed")
	r.AddCheck("processes", "PARTIAL", "ok")
	r.AddCheck("active_http_sapi_verification", "NOT_IMPLEMENTED", "Package/process/path observations cannot verify the PHP runtime actually serving HTTP traffic")
	r.AddEvidence(Evidence{
		Type: "binary_static_version", Name: "php", Version: "8.4.24",
		Source: "well-known path static binary inspection", Location: "/usr/bin/php",
		Detail:         "embedded_php_version; provenance=verified_binary_metadata; confidence=HIGH; full_file_read bytes=1024",
		Interpretation: "STATIC_BINARY_VERSION_NOT_ACTIVE_RUNTIME_ATTESTATION",
	})
	EvaluatePatchPosture(r)
	FinalizeSummary(r)
	html := EncodeHTML(r)
	out := filepath.Join(moduleRootDir(t), "docs", "assets", "report-example-patch-assessment.html")
	if err := os.WriteFile(out, html, 0644); err != nil {
		t.Fatal(err)
	}
	s := string(html)
	if !strings.Contains(s, "Scanner:</strong> "+Version) {
		t.Fatalf("expected scanner version %s in HTML", Version)
	}
	if !strings.Contains(s, "Generated by PHP2Shell "+Version) {
		t.Fatalf("expected footer version %s", Version)
	}
	t.Log("wrote", out)
}
